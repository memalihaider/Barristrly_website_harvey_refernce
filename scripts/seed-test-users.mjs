#!/usr/bin/env node
/**
 * Seed test Firebase Auth users + users / profile docs for all app roles.
 * Usage (from repo root):
 *   npm run seed:test-users
 *
 * Requires FIREBASE_SERVICE_ACCOUNT_KEY in .env.local.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { upsertAuthUser as upsertFirebaseUser, upsertRow } from "./lib/firebase-admin.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const outPath = path.join(ROOT, "apps/web/.test-accounts.local.md");

const PASSWORD = "TestBarristrly2026!";

const ACCOUNTS = [
  {
    email: "admin@barristrly.test",
    role: "platform_admin",
    displayName: "Test Super Admin",
  },
  {
    email: "mediator@barristrly.test",
    role: "mediator",
    displayName: "Test Mediator",
  },
  {
    email: "firmadmin@barristrly.test",
    role: "firm_admin",
    displayName: "Test Firm Admin",
  },
  {
    email: "lawyer@barristrly.test",
    role: "lawyer",
    displayName: "Test Lawyer",
    lawyer: true,
  },
  {
    email: "lawyer2@barristrly.test",
    role: "lawyer",
    displayName: "Test Lawyer Two",
    lawyer: true,
  },
  {
    email: "client@barristrly.test",
    role: "client",
    displayName: "Test Client",
  },
];

async function upsertAuthUser(account) {
  const user = await upsertFirebaseUser({
    email: account.email,
    password: PASSWORD,
    displayName: account.displayName,
  });
  return { id: user.uid };
}

async function upsertPublicRows(user, account) {
  await upsertRow("users", {
    id: user.id,
    email: account.email,
    role: account.role,
    status: "active",
    display_name: account.displayName,
    onboarding_completed: true,
  });

  if (account.role === "client") {
    await upsertRow("client_profiles", {
      id: user.id,
      preferred_language: "en",
      contact_preference: "platform",
    });
  }

  if (account.lawyer) {
    const initials =
      account.displayName
        .split(/\s+/)
        .map((p) => p[0])
        .join("")
        .slice(0, 3)
        .toUpperCase() || "LW";

    await upsertRow("lawyer_profiles", {
      id: user.id,
      display_name: account.displayName,
      initials,
      practice_areas: ["commercial", "corporate", "employment"],
      jurisdictions: ["AE-DU", "AE-DIFC", "AE-ADGM"],
      languages: ["en"],
      is_verified: true,
      is_public: true,
      subscription_tier: "free",
      rating: 4.7,
    });

    await upsertRow("lawyer_approvals", {
      id: user.id,
      email: account.email,
      display_name: account.displayName,
      status: "approved",
    });
  }

  if (account.role === "mediator") {
    await upsertRow("mediator_profiles", {
      id: user.id,
      display_name: account.displayName,
    });
  }
}

async function main() {
  console.log("Seeding test users into Firebase");
  const rows = [];

  for (const account of ACCOUNTS) {
    process.stdout.write(`  ${account.email} (${account.role})… `);
    const user = await upsertAuthUser(account);
    await upsertPublicRows(user, account);
    console.log("ok");
    rows.push({
      role: account.role,
      email: account.email,
      password: PASSWORD,
      displayName: account.displayName,
      id: user.id,
      portal:
        account.role === "lawyer"
          ? "/lawyer"
          : account.role === "client"
            ? "/client"
            : "/admin",
    });
  }

  const md = [
    "# Test accounts (local)",
    "",
    "Generated by `npm run seed:test-users`. Do not commit.",
    "",
    `Shared password: \`${PASSWORD}\``,
    "",
    "| Role | Email | Portal |",
    "| --- | --- | --- |",
    ...rows.map((r) => `| ${r.role} | \`${r.email}\` | ${r.portal} |`),
    "",
    "## Notes",
    "",
    "- Lawyers are **verified + public** (match pool ready).",
    "- Login at `/login`.",
    "- Super admin = `platform_admin` → `/admin`.",
    "",
  ].join("\n");

  fs.writeFileSync(outPath, md);
  console.log("\nWrote", outPath);
  console.log("\nCredentials (password for all):", PASSWORD);
  for (const r of rows) {
    console.log(`  ${r.role.padEnd(16)} ${r.email}  → ${r.portal}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
